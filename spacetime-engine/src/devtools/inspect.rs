/// UI hints for numeric input. These are presentation affordances, not domain
/// validation. Domains must still validate every edit request they accept.
#[derive(Debug, Clone, Copy)]
pub struct InspectNumberInput {
    pub speed: f64,
    pub minimum: Option<f64>,
    pub maximum: Option<f64>,
    pub slider: bool,
}

impl Default for InspectNumberInput {
    fn default() -> Self {
        Self {
            speed: 0.1,
            minimum: None,
            maximum: None,
            slider: false,
        }
    }
}

impl InspectNumberInput {
    pub const fn speed(speed: f64) -> Self {
        Self {
            speed,
            minimum: None,
            maximum: None,
            slider: false,
        }
    }

    pub const fn range(mut self, minimum: f64, maximum: f64) -> Self {
        self.minimum = Some(minimum);
        self.maximum = Some(maximum);
        self
    }

    pub const fn slider(mut self) -> Self {
        self.slider = true;
        self
    }
}

/// Static metadata generated by [`Inspect`] implementations.
///
/// This contains presentation-independent meaning only. In particular, a widget
/// override is a stable ID rather than an egui callback/function pointer.
#[derive(Debug, Clone, Copy)]
pub struct InspectFieldMetadata {
    pub id: InspectFieldId,
    pub rust_name: &'static str,
    pub rust_type_name: &'static str,
    pub label: &'static str,
    pub symbol: Option<&'static str>,
    pub access: InspectAccess,
    pub unit: Option<InspectUnit>,
    pub hint: Option<&'static str>,
    pub role: Option<&'static str>,
    pub widget: Option<InspectWidgetId>,
    pub number_input: Option<InspectNumberInput>,
}

impl InspectFieldMetadata {
    pub const fn new(
        id: InspectFieldId,
        rust_name: &'static str,
        rust_type_name: &'static str,
        label: &'static str,
    ) -> Self {
        Self {
            id,
            rust_name,
            rust_type_name,
            label,
            symbol: None,
            access: InspectAccess::ReadOnly,
            unit: None,
            hint: None,
            role: None,
            widget: None,
            number_input: None,
        }
    }
}

#[derive(Debug)]
pub struct InspectTypeMetadata {
    pub rust_name: &'static str,
    pub label: &'static str,
    pub fields: &'static [InspectFieldMetadata],
}

/// UI-agnostic field traversal for inspectable values.
///
/// The derive emits this traversal. Presentation hosts choose how to render the
/// values and whether they possess a legal edit capability.
pub trait InspectFieldVisitor {
    fn field(&mut self, metadata: &'static InspectFieldMetadata, value: &dyn Any);
}

/// Mutable traversal deliberately exposes `&mut` only for fields whose metadata
/// declares [`InspectAccess::Direct`]. Validated/transactional/command fields are
/// visited through `read_only` and require an explicit adapter/request path.
pub trait InspectFieldVisitorMut {
    fn read_only(&mut self, metadata: &'static InspectFieldMetadata, value: &dyn Any);
    fn direct(&mut self, metadata: &'static InspectFieldMetadata, value: &mut dyn Any);
}

/// Type-level opt-in for reusable structured inspection.
///
/// `#[derive(Inspect)]` implements this trait for ordinary named-field structs.
/// Manual implementations remain a first-class path for computed properties,
/// setters, polymorphism, collections, or any type whose semantics are richer
/// than stored fields.
pub trait Inspect: Any {
    fn inspect_type_metadata() -> &'static InspectTypeMetadata
    where
        Self: Sized;

    fn visit_inspect_fields(&self, visitor: &mut dyn InspectFieldVisitor);
    fn visit_inspect_fields_mut(&mut self, visitor: &mut dyn InspectFieldVisitorMut);
}

#[derive(Clone, Copy)]
pub struct InspectTypeRegistration {
    type_id: TypeId,
    metadata: &'static InspectTypeMetadata,
    visit: fn(&dyn Any, &mut dyn InspectFieldVisitor) -> bool,
    visit_mut: fn(&mut dyn Any, &mut dyn InspectFieldVisitorMut) -> bool,
}

impl InspectTypeRegistration {
    fn of<T: Inspect>() -> Self {
        Self {
            type_id: TypeId::of::<T>(),
            metadata: T::inspect_type_metadata(),
            visit: visit_erased::<T>,
            visit_mut: visit_erased_mut::<T>,
        }
    }

    pub fn type_id(self) -> TypeId {
        self.type_id
    }

    pub fn metadata(self) -> &'static InspectTypeMetadata {
        self.metadata
    }

    pub fn visit(self, value: &dyn Any, visitor: &mut dyn InspectFieldVisitor) -> bool {
        (self.visit)(value, visitor)
    }

    pub fn visit_mut(
        self,
        value: &mut dyn Any,
        visitor: &mut dyn InspectFieldVisitorMut,
    ) -> bool {
        (self.visit_mut)(value, visitor)
    }
}

fn visit_erased<T: Inspect>(value: &dyn Any, visitor: &mut dyn InspectFieldVisitor) -> bool {
    let Some(value) = value.downcast_ref::<T>() else {
        return false;
    };
    value.visit_inspect_fields(visitor);
    true
}

fn visit_erased_mut<T: Inspect>(
    value: &mut dyn Any,
    visitor: &mut dyn InspectFieldVisitorMut,
) -> bool {
    let Some(value) = value.downcast_mut::<T>() else {
        return false;
    };
    value.visit_inspect_fields_mut(visitor);
    true
}

/// Runtime catalog for externally registered inspectable Rust types.
///
/// Registration is explicit: deriving [`Inspect`] describes a type, while an app
/// registers only the types it wants discoverable through type erasure.
#[derive(Resource, Default)]
pub struct InspectTypeRegistry {
    registrations: HashMap<TypeId, InspectTypeRegistration>,
}

impl InspectTypeRegistry {
    pub fn register<T: Inspect>(&mut self) {
        self.registrations
            .entry(TypeId::of::<T>())
            .or_insert_with(InspectTypeRegistration::of::<T>);
    }

    pub fn get<T: Inspect>(&self) -> Option<InspectTypeRegistration> {
        self.get_by_type_id(TypeId::of::<T>())
    }

    pub fn get_by_type_id(&self, type_id: TypeId) -> Option<InspectTypeRegistration> {
        self.registrations.get(&type_id).copied()
    }

    pub fn registrations(&self) -> impl Iterator<Item = InspectTypeRegistration> + '_ {
        self.registrations.values().copied()
    }
}

pub trait AppInspectExt {
    fn register_inspectable<T: Inspect>(&mut self) -> &mut Self;
}

impl AppInspectExt for App {
    fn register_inspectable<T: Inspect>(&mut self) -> &mut Self {
        self.init_resource::<InspectTypeRegistry>();
        self.world_mut()
            .resource_mut::<InspectTypeRegistry>()
            .register::<T>();
        self
    }
}

#[derive(Debug, Clone)]
pub enum InspectValue {
    Text(String),
    Bool(bool),
    Integer(i64),
    Number {
        value: f64,
        format: InspectNumberFormat,
    },
    Quantity {
        value: f64,
        unit: InspectUnit,
        format: InspectNumberFormat,
    },
    Range {
        minimum: f64,
        maximum: f64,
        unit: InspectUnit,
        format: InspectNumberFormat,
    },
    Entity(Entity),
    Vec3(Vec3),
}

impl InspectValue {
    pub fn text(value: impl Into<String>) -> Self {
        Self::Text(value.into())
    }

    pub fn number(value: impl Into<f64>) -> Self {
        Self::Number {
            value: value.into(),
            format: InspectNumberFormat::default(),
        }
    }

    pub fn quantity(value: impl Into<f64>, unit: InspectUnit) -> Self {
        Self::Quantity {
            value: value.into(),
            unit,
            format: InspectNumberFormat::default(),
        }
    }

    pub fn quantity_with_format(
        value: impl Into<f64>,
        unit: InspectUnit,
        format: InspectNumberFormat,
    ) -> Self {
        Self::Quantity {
            value: value.into(),
            unit,
            format,
        }
    }

    pub fn as_number(&self) -> Option<f64> {
        match self {
            Self::Number { value, .. } | Self::Quantity { value, .. } => Some(*value),
            _ => None,
        }
    }
}

#[derive(Debug, Clone)]
pub struct InspectField {
    pub id: Option<InspectFieldId>,
    pub label: String,
    pub symbol: Option<&'static str>,
    pub value: InspectValue,
    pub access: InspectAccess,
    pub hint: Option<String>,
    pub number_input: Option<InspectNumberInput>,
}

impl InspectField {
    pub fn new(label: impl Into<String>, value: InspectValue) -> Self {
        Self {
            id: None,
            label: label.into(),
            symbol: None,
            value,
            access: InspectAccess::ReadOnly,
            hint: None,
            number_input: None,
        }
    }

    pub fn symbol(mut self, symbol: &'static str) -> Self {
        self.symbol = Some(symbol);
        self
    }

    pub fn access(mut self, access: InspectAccess) -> Self {
        self.access = access;
        self
    }

    pub fn editable(mut self, id: InspectFieldId, access: InspectAccess) -> Self {
        debug_assert!(access.editable());
        self.id = Some(id);
        self.access = access;
        self
    }

    pub fn hint(mut self, hint: impl Into<String>) -> Self {
        self.hint = Some(hint.into());
        self
    }

    pub fn number_input(mut self, input: InspectNumberInput) -> Self {
        self.number_input = Some(input);
        self
    }
}

