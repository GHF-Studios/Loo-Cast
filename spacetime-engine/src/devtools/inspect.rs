#[derive(Debug, Clone)]
pub struct InspectSection {
    pub id: InspectSectionId,
    pub title: String,
    pub order: i32,
    pub structure_item: Option<StructureItemId>,
    pub contextual_gizmo: bool,
    pub fields: Vec<InspectField>,
    pub actions: Vec<InspectAction>,
}

impl InspectSection {
    pub fn new(id: InspectSectionId, title: impl Into<String>, order: i32) -> Self {
        Self {
            id,
            title: title.into(),
            order,
            structure_item: None,
            contextual_gizmo: false,
            fields: Vec::new(),
            actions: Vec::new(),
        }
    }

    pub fn for_structure(mut self, structure_item: StructureItemId) -> Self {
        self.structure_item = Some(structure_item);
        self
    }

    pub fn contextual_gizmo(mut self) -> Self {
        self.contextual_gizmo = true;
        self
    }

    pub fn field(mut self, field: InspectField) -> Self {
        self.fields.push(field);
        self
    }

    pub fn action(mut self, action: InspectAction) -> Self {
        self.actions.push(action);
        self
    }
}

/// Proposed semantic field edit emitted by an inspection UI host.
///
/// This is a request, never authority. The owning domain must re-check target,
/// access, invariants and persistence semantics before applying it.
#[derive(Message, Debug, Clone)]
pub struct InspectEditRequest {
    pub target: FocusTarget,
    pub section: InspectSectionId,
    pub field: InspectFieldId,
    pub value: InspectValue,
}

/// Contextual operation emitted by an inspection/gizmo UI host.
#[derive(Message, Debug, Clone, Copy)]
pub struct InspectActionRequest {
    pub target: FocusTarget,
    pub section: InspectSectionId,
    pub action: InspectActionId,
}

/// One frame of structured semantic inspection data for the canonical focus.
#[derive(Resource, Debug, Default)]
pub struct InspectionFrame {
    sections: Vec<InspectSection>,
}

impl InspectionFrame {
    pub fn submit(&mut self, section: InspectSection) {
        assert!(
            !self.sections.iter().any(|existing| existing.id == section.id),
            "duplicate inspection section id {}",
            section.id.0,
        );
        self.sections.push(section);
    }

    pub fn sections(&self) -> &[InspectSection] {
        &self.sections
    }

    pub fn section(&self, id: InspectSectionId) -> Option<&InspectSection> {
        self.sections.iter().find(|section| section.id == id)
    }

    pub fn sorted_sections(&self) -> Vec<&InspectSection> {
        self.sorted_sections_for(None)
    }

    /// `None` means whole-entity inspection and therefore returns all sections.
    pub fn sorted_sections_for(&self, structure_item: Option<StructureItemId>) -> Vec<&InspectSection> {
        let mut sections = self
            .sections
            .iter()
            .filter(|section| {
                structure_item.is_none() || section.structure_item == structure_item
            })
            .collect::<Vec<_>>();
        sections.sort_by(|a, b| {
            a.order
                .cmp(&b.order)
                .then_with(|| a.title.cmp(&b.title))
        });
        sections
    }

    fn clear(&mut self) {
        self.sections.clear();
    }
}

pub(super) fn clear_inspection_frame(mut frame: ResMut<InspectionFrame>) {
    frame.clear();
}

#[cfg(test)]
mod inspect_derive_tests {
    use std::any::Any;

    use super::*;

    #[derive(crate::Inspect)]
    #[inspect(label = "Derived example")]
    struct DerivedExample {
        #[inspect(
            direct,
            label = "Opacity",
            role = "opacity",
            widget = "tests.opacity",
            speed = 0.01,
            range = 0.0..=1.0,
            slider
        )]
        opacity: f32,
        #[inspect(validated, unit = "K", hint = "Validation belongs to the domain adapter.")]
        temperature_kelvin: f32,
        #[inspect(skip)]
        cache: u32,
    }

    struct MutabilityProbe {
        direct: usize,
        read_only: usize,
    }

    impl InspectFieldVisitorMut for MutabilityProbe {
        fn read_only(&mut self, _: &'static InspectFieldMetadata, _: &dyn Any) {
            self.read_only += 1;
        }

        fn direct(&mut self, _: &'static InspectFieldMetadata, value: &mut dyn Any) {
            self.direct += 1;
            *value
                .downcast_mut::<f32>()
                .expect("the direct test field is f32") = 0.75;
        }
    }

    #[test]
    fn derive_describes_fields_without_leaking_non_direct_mutability() {
        let metadata = DerivedExample::inspect_type_metadata();
        assert_eq!(metadata.label, "Derived example");
        assert_eq!(metadata.fields.len(), 2);

        let opacity = metadata.fields[0];
        assert_eq!(opacity.id, InspectFieldId("opacity"));
        assert_eq!(opacity.label, "Opacity");
        assert_eq!(opacity.role, Some("opacity"));
        assert_eq!(opacity.widget, Some(InspectWidgetId("tests.opacity")));
        assert_eq!(opacity.access, InspectAccess::Direct);
        assert!(opacity.number_input.expect("numeric metadata").slider);

        let temperature = metadata.fields[1];
        assert_eq!(temperature.access, InspectAccess::Validated);
        assert_eq!(temperature.unit, Some(InspectUnit::KELVIN));

        let mut value = DerivedExample {
            opacity: 0.25,
            temperature_kelvin: 350.0,
            cache: 7,
        };
        let mut probe = MutabilityProbe {
            direct: 0,
            read_only: 0,
        };
        value.visit_inspect_fields_mut(&mut probe);

        assert_eq!(probe.direct, 1);
        assert_eq!(probe.read_only, 1);
        assert_eq!(value.opacity, 0.75);
        assert_eq!(value.temperature_kelvin, 350.0);
        assert_eq!(value.cache, 7);
    }
}
